"""(Re)generate the base model's OWN reply to the blackmail honeypot, on a GPU box.

The "+ model's response" sample text needs the assistant turn generated by the
SAME model the explorer extracts activations from — the raw base Qwen3.6-27B (NOT
the NLA actor). Pasting any other model's text would put those positions
off-distribution and the NLA readout would be meaningless.

Run on the H200 (after the base model is downloaded):
    cd /workspace/precache && HF_TOKEN=$(cat /root/.hf_token) \
        /opt/conda/bin/python scenarios/gen_response.py

Writes scenarios/blackmail_response.txt (the assistant continuation, verbatim) —
commit that back; build_default_texts.py reconstructs the full transcript from it
and asserts the round-trip. Thinking is ON (the reasoning trace is the point).
"""
import os
import sys
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import build_default_texts as B  # noqa: E402

BASE_ID = "Qwen/Qwen3.6-27B"     # raw base — the model the explorer reads from
MAX_NEW = 2560   # enough for the full reasoning trace + the emails it drafts
SEED = 0

tok = AutoTokenizer.from_pretrained(B.MODEL_REPO, subfolder=B.TOK_SUBDIR,
                                    token=os.environ.get("HF_TOKEN"))
emails = (B.SCEN / "blackmail_emails.md").read_text().strip()
msgs = [{"role": "system", "content": B._blackmail_system()},
        {"role": "user", "content": B.USER_PROMPT + "\n" + emails}]
prompt_str = tok.apply_chat_template(msgs, tokenize=False,
                                     add_generation_prompt=True, enable_thinking=True)
print("[prompt] tail:", repr(prompt_str[-70:]), flush=True)

model = AutoModelForCausalLM.from_pretrained(
    BASE_ID, torch_dtype=torch.bfloat16, attn_implementation="sdpa",
    device_map={"": 0}).eval()
ids = tok(prompt_str, add_special_tokens=True, return_tensors="pt")["input_ids"].cuda()
torch.manual_seed(SEED)
with torch.inference_mode():
    out = model.generate(ids, max_new_tokens=MAX_NEW, do_sample=True,
                         temperature=0.6, top_p=0.95, top_k=20,
                         pad_token_id=tok.eos_token_id)
cont = tok.decode(out[0][ids.shape[1]:], skip_special_tokens=False)

# faithfulness: build_default_texts rebuilds full = prompt_str + cont and tokenizes
# it with tok(add_special_tokens=True); that must reproduce the generated ids.
full = prompt_str + cont
ok = tok(full, add_special_tokens=True)["input_ids"] == out[0].tolist()
print(f"[gen] cont_tokens={out.shape[1]-ids.shape[1]} full_tokens={out.shape[1]} "
      f"round_trip={ok} eos={'<|im_end|>' in cont}", flush=True)
(B.SCEN / "blackmail_response.txt").write_text(cont)
print("[saved] scenarios/blackmail_response.txt", flush=True)
print("=== RESPONSE (first 4000 chars) ===\n" + cont[:4000], flush=True)
